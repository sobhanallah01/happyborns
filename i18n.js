// ---- runtime ----
(function(){
  const KNOWN = HB_LANGS.map(l => l.code);
  function pick() {
    // Returning visitor: honour their saved choice.
    const saved = localStorage.getItem('hb_lang');
    if (saved && KNOWN.includes(saved)) return saved;
    // First visit: always default to English (Western-first launch).
    return 'en';
  }

  window.hbLang = pick();
  window.hbT = function(key) {
    const d = HB_I18N[window.hbLang] || {};
    return (key in d) ? d[key] : HB_I18N.en[key];
  };

  window.hbApply = function(code) {
    if (code && KNOWN.includes(code)) {
      window.hbLang = code;
      localStorage.setItem('hb_lang', code);
    }
    const html = document.documentElement;
    html.lang = window.hbLang;
    html.dir = HB_RTL.includes(window.hbLang) ? 'rtl' : 'ltr';

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const v = window.hbT(el.getAttribute('data-i18n'));
      if (v != null) el.textContent = v;
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const v = window.hbT(el.getAttribute('data-i18n-html'));
      if (v != null) el.innerHTML = v;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const v = window.hbT(el.getAttribute('data-i18n-ph'));
      if (v != null) el.setAttribute('placeholder', v);
    });
    // notify page scripts that depend on language (dynamic strings)
    document.dispatchEvent(new CustomEvent('hb:lang', { detail: window.hbLang }));
  };

  document.addEventListener('DOMContentLoaded', function(){
    // build the top switcher
    const sel = document.getElementById('lang-switch');
    if (sel) {
      HB_LANGS.forEach(l => {
        const o = document.createElement('option');
        o.value = l.code; o.textContent = l.name;
        sel.appendChild(o);
      });
      sel.value = window.hbLang;
      sel.addEventListener('change', function(){
        window.hbApply(this.value);
        const pref = document.getElementById('inp-lang');
        if (pref) pref.value = this.value;
      });
    }
    // build the in-form "preferred language" field, synced both ways
    const pref = document.getElementById('inp-lang');
    if (pref) {
      HB_LANGS.forEach(l => {
        const o = document.createElement('option');
        o.value = l.code; o.textContent = l.name;
        pref.appendChild(o);
      });
      pref.value = window.hbLang;
      pref.addEventListener('change', function(){
        window.hbApply(this.value);
        if (sel) sel.value = this.value;
      });
    }
    window.hbApply(window.hbLang);
  });
})();
